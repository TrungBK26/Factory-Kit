using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// Quản lý cơ chế vác đồ xếp chồng trên đỉnh đầu của Người chơi (Head-Stack Carry System).
/// Triển khai interface ICarryable để dùng chung logic với SellZone và StoragePad.
/// </summary>
public class PlayerCarry : MonoBehaviour, ICarryable
{
    [Header("--- VỊ TRÍ GẮN ĐỒ & XẾP CHỒNG ---")]
    [Tooltip("Vị trí điểm gắn trên đầu nhân vật (Y = 1.2m trên Capsule hoặc Head Bone)")]
    [SerializeField] private Transform headSocket;

    [Tooltip("Khoảng cách dãn cách xếp chồng theo trục Y (m)")]
    [SerializeField] private float stackOffset = 0.4f;

    [Tooltip("Sức chứa tối đa của người chơi")]
    [SerializeField] private int maxCapacity = 5;

    private readonly List<GameObject> carriedItems = new List<GameObject>();
    private Animator animator;
    private static readonly int IsCarryingHash = Animator.StringToHash("isCarrying");

    public bool CanCarryMore => carriedItems.Count < maxCapacity;
    public int CurrentCount => carriedItems.Count;
    public int MaxCapacity => maxCapacity;

    private void Awake()
    {
        // Tự tìm Animator nếu có
        if (animator == null) animator = GetComponentInChildren<Animator>();

        // Fallback: nếu chưa gán headSocket, tạo một Empty GameObject tại đỉnh đầu
        if (headSocket == null)
        {
            GameObject socketObj = new GameObject("CarrySocket_AutoGenerated");
            socketObj.transform.SetParent(transform);
            socketObj.transform.localPosition = new Vector3(0f, 1.85f, 0f);
            socketObj.transform.localRotation = Quaternion.identity;
            headSocket = socketObj.transform;
        }
    }

    public void AddItem(GameObject itemObj)
    {
        if (!CanCarryMore || itemObj == null) return;

        // Triệt tiêu vật lý và tắt Collider để tiết kiệm 100% CPU Physics
        if (itemObj.TryGetComponent<Collider>(out var col)) col.enabled = false;
        if (itemObj.TryGetComponent<Rigidbody>(out var rb)) rb.isKinematic = true;

        itemObj.transform.SetParent(headSocket);
        itemObj.transform.localPosition = new Vector3(0f, carriedItems.Count * stackOffset, 0f);
        itemObj.transform.localRotation = Quaternion.identity;

        carriedItems.Add(itemObj);

        // Kích hoạt layer hoạt ảnh vác đồ nếu có Animator
        if (animator != null && animator.runtimeAnimatorController != null)
        {
            animator.SetBool(IsCarryingHash, true);
        }

        GameEvents.OnItemPickedUp?.Invoke(carriedItems.Count);
        Debug.Log($"[Player] Đã vác vật phẩm: {carriedItems.Count}/{maxCapacity}");
    }

    public GameObject PopTopItem()
    {
        if (carriedItems.Count == 0) return null;

        int lastIndex = carriedItems.Count - 1;
        GameObject item = carriedItems[lastIndex];
        carriedItems.RemoveAt(lastIndex);

        if (carriedItems.Count == 0 && animator != null && animator.runtimeAnimatorController != null)
        {
            animator.SetBool(IsCarryingHash, false);
        }

        return item;
    }

    public List<GameObject> ClearAndTakeAllItems()
    {
        var items = new List<GameObject>(carriedItems);
        carriedItems.Clear();

        if (animator != null && animator.runtimeAnimatorController != null)
        {
            animator.SetBool(IsCarryingHash, false);
        }

        return items;
    }
}
